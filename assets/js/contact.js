/* Account application form: client-side validation, request-list summary, and
   submission.

   Submission is chosen by TR_FORM_PROVIDER at build time:
     netlify   POST the form urlencoded to its own page; Netlify captures it.
     endpoint  POST JSON to TR_FORM_ENDPOINT (your own handler or a service).
     anything else, or a failed POST, falls back to showing the composed
     enquiry so the visitor can copy or email it. The fallback is a safety net,
     not a configuration: it leaves you no record of the lead. */
(function () {
  'use strict';

  /* Configuration comes from assets/js/config.js, generated by tools/build.py.
     Set TR_FORM_ENDPOINT and TR_CONTACT_EMAIL in the build environment. */
  var CFG = window.TR_CONFIG || {};
  var PROVIDER = CFG.formProvider || '';
  var ENDPOINT = CFG.formEndpoint || null;
  var CONTACT_EMAIL = CFG.contactEmail || 'accounts@timelessresearch.com';

  var form = document.getElementById('account-form');
  if (!form) return;

  var status = document.getElementById('form-status');
  var esc = window.TR_esc || function (s) { return String(s); };

  /* ---- show the request list alongside the form ------------------------- */
  var list = (window.TR_RFQ && window.TR_RFQ.all()) || [];
  var summary = document.getElementById('rfq-summary');
  var summaryBody = document.getElementById('rfq-summary-body');
  if (list.length && summary && summaryBody) {
    summary.hidden = false;
    summaryBody.innerHTML = list.map(function (i) {
      return '<div style="display:flex;justify-content:space-between;gap:1rem;padding:.5rem 0;border-bottom:1px solid var(--line)">' +
        '<span>' + esc(i.name) + '</span>' +
        '<span class="mono muted" style="font-size:.72rem">' + esc(i.size) + ' &times;' + i.qty + '</span></div>';
    }).join('');
  }

  /* ---- validation ------------------------------------------------------- */
  function fieldOf(el) { return el.closest('.field'); }

  function validate() {
    var ok = true;
    form.querySelectorAll('[required]').forEach(function (el) {
      var valid = el.type === 'checkbox' ? el.checked : el.value.trim() !== '';
      if (valid && el.type === 'email') valid = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(el.value.trim());
      // accept any international format, but require enough digits to be a real number
      if (valid && el.type === 'tel') valid = (el.value.replace(/\D/g, '').length >= 7);
      var f = fieldOf(el);
      if (f) f.classList.toggle('is-invalid', !valid);
      if (!valid && ok) { el.focus(); ok = false; }
    });
    return ok;
  }

  form.addEventListener('submit', function (e) {
    e.preventDefault();
    if (!validate()) {
      if (status) status.innerHTML = '<p class="muted" style="color:#FF8A8A;font-size:.8rem">Please correct the highlighted fields.</p>';
      return;
    }

    var requested = list.map(function (i) { return i.name + ' ' + i.size + ' x' + i.qty; });
    var listField = document.getElementById('f-request-list');
    if (listField) listField.value = requested.join('\n');

    var data = {};
    new FormData(form).forEach(function (v, k) { data[k] = v; });
    data.request_list = requested;

    var lines = [
      'Name: ' + (data.name || ''),
      'Email: ' + (data.email || ''),
      'Phone: ' + (data.phone || ''),
      '',
      'Confirmed in vitro research use only: yes'
    ];
    if (data.request_list.length) {
      lines.push('', 'Request list:', data.request_list.join('\n'));
    }
    var body = lines.join('\n');
    var subject = 'Enquiry \u2014 ' + (data.name || '');

    /* No endpoint, or the POST failed: show the enquiry so the visitor can copy
       or email it. A bare mailto: redirect silently does nothing when no mail
       client is configured, which loses the lead without either side knowing. */
    function showManualFallback(reason) {
      if (!status) return;
      var mailto = 'mailto:' + CONTACT_EMAIL +
        '?subject=' + encodeURIComponent(subject) +
        '&body=' + encodeURIComponent(body);
      status.innerHTML =
        '<div style="border:1px solid var(--line-strong);border-radius:12px;padding:1.25rem;margin-top:.5rem">' +
        '<p style="font-size:.85rem;margin-bottom:.75rem">' + esc(reason) + '</p>' +
        '<pre id="enquiry-text" style="white-space:pre-wrap;font-family:var(--f-mono);font-size:.72rem;' +
        'line-height:1.6;background:var(--tile);padding:.9rem;border-radius:8px;margin-bottom:.9rem">' +
        esc(body) + '</pre>' +
        '<div style="display:flex;gap:.6rem;flex-wrap:wrap">' +
        '<button type="button" class="btn btn--ghost btn--sm" id="copy-enquiry">Copy details</button>' +
        '<a class="btn btn--primary btn--sm" href="' + mailto + '">Open in email</a>' +
        '</div>' +
        '<p class="muted" style="font-size:.72rem;margin-top:.8rem">Or send it to ' +
        '<a href="mailto:' + CONTACT_EMAIL + '" style="color:var(--accent);text-decoration:underline">' +
        CONTACT_EMAIL + '</a>.</p></div>';
      var copyBtn = document.getElementById('copy-enquiry');
      if (copyBtn) {
        copyBtn.addEventListener('click', function () {
          var done = function () { copyBtn.textContent = 'Copied'; setTimeout(function () { copyBtn.textContent = 'Copy details'; }, 1800); };
          if (navigator.clipboard && navigator.clipboard.writeText) {
            navigator.clipboard.writeText(body).then(done, selectInstead);
          } else { selectInstead(); }
        });
      }
      function selectInstead() {
        var pre = document.getElementById('enquiry-text');
        if (!pre) return;
        var r = document.createRange(); r.selectNodeContents(pre);
        var sel = window.getSelection(); sel.removeAllRanges(); sel.addRange(r);
      }
    }

    var netlify = PROVIDER === 'netlify';
    if (!netlify && !ENDPOINT) {
      showManualFallback('No submission endpoint is configured yet. Copy your details below, or open them in your email client.');
      return;
    }

    /* Netlify captures a form posted urlencoded back to its own page, keyed by
       the form-name field. Anything else takes the JSON endpoint. */
    var url = netlify ? window.location.pathname : ENDPOINT;
    var opts = netlify
      ? { method: 'POST',
          headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
          body: new URLSearchParams(new FormData(form)).toString() }
      : { method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(data) };

    var btn = form.querySelector('button[type="submit"]');
    btn.disabled = true;
    if (status) status.innerHTML = '<p class="muted" style="font-size:.8rem">Sending\u2026</p>';
    fetch(url, opts).then(function (r) {
      if (!r.ok) throw new Error('HTTP ' + r.status);
      form.reset();
      if (status) status.innerHTML =
        '<p style="color:var(--ok);font-size:.85rem">Thank you \u2014 we will be in touch within two business days.</p>';
    }).catch(function () {
      showManualFallback('That could not be sent automatically. Copy your details below, or open them in your email client \u2014 nothing has been lost.');
    }).finally(function () { btn.disabled = false; });
  });
})();
